// URL-safe page slug: "Nidoran♀" -> "nidoran-f", "Mr. Mime" -> "mr-mime", "Farfetch'd" -> "farfetchd".
export function getPokemonSlug(name: string): string {
  return name
    .toLowerCase()
    .replace('♀', '-f')
    .replace('♂', '-m')
    .replace(/['’.]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

